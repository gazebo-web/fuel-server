// ModelInfo describes one project model (project_list_models and
// GET /projects/{name}/models).
type ModelInfo struct {
	Name        string `json:"name"`
	URI         string `json:"uri"`
	Path        string `json:"path"`
	Description string `json:"description,omitempty"`
	Static      bool   `json:"static,omitempty"`
	Links       int    `json:"links,omitempty"`
	Joints      int    `json:"joints,omitempty"`
	Shape       string `json:"shape,omitempty"`
	Generated   bool   `json:"generated,omitempty"`
	Preview     string `json:"preview,omitempty"`
	Files       int    `json:"files"`
	Problem     string `json:"problem,omitempty"`
}

func (t *tools) projectListModels(tc *mcp.ToolContext, args map[string]any) (mcp.CallToolResult, error) {
	v, errRes := requireStrings(args, "name")
	if errRes != nil {
		return *errRes, nil
	}
	rev, models, em := ListProjectModels(tc.Ctx, tc.DB, tc.User, v[0], argString(args, "rev"))
	if em != nil {
		return gzError(em), nil
	}
	return jsonResult(map[string]any{"rev": rev, "models": models})
}

// ListProjectModels lists the models in models/<name>/ at rev ("" = HEAD)
// of the caller's project, and the resolved revision.
func ListProjectModels(ctx context.Context, tx *gorm.DB, user *users.User, project, rev string) (string, []ModelInfo, *gz.ErrMsg) {
	files, rev, em := projectService.ListFiles(ctx, tx, *user.Username, project, rev, user)
	if em != nil {
		return "", nil, em
	}
	pf := newProjectFiles("", files)
	read := func(p string) (string, bool) {
		b, _, em := projectService.ReadFile(ctx, tx, *user.Username, project, p, rev, user)
		return string(b), em == nil
	}
	out := []ModelInfo{}
	for _, name := range pf.models() {
		dir := path.Join(modelsDir, name)
		mi := ModelInfo{Name: name, URI: "model://" + name, Path: dir}
		for f := range pf.files {
			if strings.HasPrefix(f, dir+"/") {
				mi.Files++
				if strings.HasPrefix(f, dir+"/source/") {
					mi.Generated = true
				}
				if strings.HasPrefix(f, dir+"/previews/") && strings.HasSuffix(f, ".png") && mi.Preview == "" {
					mi.Preview = f
				}
			}
		}
		if c, ok := read(dir + "/model.config"); ok {
			var mc modelConfig
			if xml.Unmarshal([]byte(c), &mc) == nil {
				mi.Description = strings.TrimSpace(mc.Description)
			}
		}
		if s, ok := read(dir + "/model.sdf"); !ok {
			mi.Problem = "no model.sdf"
		} else if sum, err := sdf.Summarize(s); err != nil {
			mi.Problem = "model.sdf: " + err.Error()
		} else if len(sum.Entities) > 0 {
			e := sum.Entities[0]
			mi.Static, mi.Links, mi.Joints, mi.Shape = e.Static, e.Links, e.Joints, e.Shape
		}
		out = append(out, mi)
	}
	return rev, out, nil
}
