"""Model folder output (plan §5.4): GLB visual, collision GLBs, model.sdf,
model.config.

Vertices are written in Gazebo's frame (Z up, +X forward) with no root
node rotation: Gazebo's assimp loader and gzweb's GLTFLoader both use glTF
coordinates as-is (meshworker/spike/README.md).
"""

import os
from xml.sax.saxutils import escape

import numpy as np
import trimesh

from .collision import Shape
from .inertia import Inertial


def num(x: float) -> str:
    return f"{float(x):.6g}"


def pose(p) -> str:
    return " ".join(num(v) for v in p)


def write_glb(mesh: trimesh.Trimesh, path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(trimesh.exchange.gltf.export_glb(trimesh.Scene(mesh), include_normals=True))


def collision_xml(i: int, s: Shape, name: str) -> str:
    if s.kind == "box":
        geom = f"<box><size>{pose(s.size)}</size></box>"
    elif s.kind == "cylinder":
        geom = f"<cylinder><radius>{num(s.radius)}</radius><length>{num(s.length)}</length></cylinder>"
    elif s.kind == "sphere":
        geom = f"<sphere><radius>{num(s.radius)}</radius></sphere>"
    else:
        geom = f"<mesh><uri>meshes/{name}_collision_{i}.glb</uri></mesh>"
    p = f"\n        <pose>{pose(s.pose)}</pose>" if any(abs(v) > 1e-12 for v in s.pose) else ""
    return f"""      <collision name="collision_{i}">{p}
        <geometry>{geom}</geometry>
      </collision>"""


def model_sdf(name: str, sdf_version: str, static: bool, inertial: Inertial, shapes: list[Shape]) -> str:
    I, c = inertial.inertia, inertial.center
    collisions = "\n".join(collision_xml(i, s, name) for i, s in enumerate(shapes))
    return f"""<?xml version="1.0"?>
<!-- Generated by the AI Builder mesh worker from source/model.py.
     Edit the source and regenerate; don't edit the meshes. -->
<sdf version="{sdf_version}">
  <model name="{name}">
    <static>{"true" if static else "false"}</static>
    <link name="link">
      <inertial>
        <pose>{pose([*c, 0, 0, 0])}</pose>
        <mass>{num(inertial.mass)}</mass>
        <inertia>
          <ixx>{num(I[0, 0])}</ixx><ixy>{num(I[0, 1])}</ixy><ixz>{num(I[0, 2])}</ixz>
          <iyy>{num(I[1, 1])}</iyy><iyz>{num(I[1, 2])}</iyz>
          <izz>{num(I[2, 2])}</izz>
        </inertia>
      </inertial>
      <visual name="visual">
        <geometry><mesh><uri>meshes/{name}.glb</uri></mesh></geometry>
      </visual>
{collisions}
    </link>
  </model>
</sdf>
"""


def model_config(name: str, sdf_version: str, description: str) -> str:
    return f"""<?xml version="1.0"?>
<model>
  <name>{escape(name)}</name>
  <version>1.0</version>
  <sdf version="{sdf_version}">model.sdf</sdf>
  <author><name>AI Builder</name></author>
  <description>{escape(description)}</description>
</model>
"""


def write_model(root: str, name: str, *, visual: trimesh.Trimesh, shapes: list[Shape], inertial: Inertial,
                static: bool, sdf_version: str, description: str, source: str) -> list[str]:
    """Writes the model folder under root; returns the paths written,
    relative to root."""
    files = {}
    write_glb(visual, os.path.join(root, "meshes", f"{name}.glb"))
    files[f"meshes/{name}.glb"] = True
    for i, s in enumerate(shapes):
        if s.kind == "mesh":
            write_glb(s.mesh, os.path.join(root, "meshes", f"{name}_collision_{i}.glb"))
            files[f"meshes/{name}_collision_{i}.glb"] = True
    texts = {
        "model.sdf": model_sdf(name, sdf_version, static, inertial, shapes),
        "model.config": model_config(name, sdf_version, description),
        "source/model.py": source,
    }
    for rel, text in texts.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        files[rel] = True
    return sorted(files)


def translate_shapes(shapes: list[Shape], offset: np.ndarray):
    for s in shapes:
        if s.kind == "mesh":
            s.mesh.apply_translation(offset)
        else:
            s.pose[:3] = [float(a + b) for a, b in zip(s.pose[:3], offset)]
